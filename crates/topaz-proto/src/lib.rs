//! Wire types for the Topaz network engine and coordination server.
//!
//! Data-plane mux frames use length-prefixed postcard; coordination HTTP uses JSON.

pub mod auth;
pub mod mux;
pub mod stun;

use serde::{Deserialize, Serialize};

pub use auth::{DeviceCert, DeviceEntry, Revocation};

/// Soft upper bound for a single framed message.
pub const MAX_FRAME_BYTES: usize = 2_000_000;

/// Control-plane HTTP/WS API version.
pub const API_VERSION: u16 = 1;

/// Package semantic version.
pub const VERSION: &str = env!("CARGO_PKG_VERSION");
/// Git commit SHA captured at build time.
pub const GIT_SHA: &str = env!("TOPAZ_GIT_SHA");
/// UTC ISO-8601 build timestamp.
pub const BUILD_TIME: &str = env!("TOPAZ_BUILD_TIME");
/// Target triple captured at build time.
pub const BUILD_TARGET: &str = env!("TOPAZ_BUILD_TARGET");
/// Full version string for `--version` and logs.
pub const VERSION_LONG: &str = env!("TOPAZ_VERSION_LONG");

/// HTTP response header carrying the coord binary version string.
pub const HDR_VERSION: &str = "x-topaz-version";
/// HTTP header carrying the one-time token required to fetch `GET /v1/enroll/{np}/finish`.
pub const HDR_ENROLL_TOKEN: &str = "x-topaz-enroll-token";

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct ServerVersion {
    pub version: String,
    pub git_sha: String,
    pub build_time: String,
    pub target: String,
    pub api_version: u16,
    pub mux_version: u8,
}

impl ServerVersion {
    pub fn current() -> Self {
        Self {
            version: VERSION.to_string(),
            git_sha: GIT_SHA.to_string(),
            build_time: BUILD_TIME.to_string(),
            target: BUILD_TARGET.to_string(),
            api_version: API_VERSION,
            mux_version: mux::MUX_VERSION,
        }
    }

    pub fn display_line(&self) -> String {
        format!(
            "{} ({} {} {}) [api=v{} mux=v{}]",
            self.version,
            self.git_sha,
            self.build_time,
            self.target,
            self.api_version,
            self.mux_version
        )
    }
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct ServerInfo {
    pub version: ServerVersion,
    pub server_time_unix: u64,
    pub relay: String,
    pub relay_ws: String,
    #[serde(default)]
    pub relay_quic: String,
    #[serde(default)]
    pub stun: String,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct CreateAccountRequest {
    pub invite: String,
    /// First device, issued by the root key.
    pub cert: DeviceCert,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct RegisterRequest {
    pub endpoints: Vec<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct RegisterResponse {
    pub observed_ip: String,
    pub relay: String,
    /// TLS-wrapped WebSocket relay, e.g. `wss://host:7722/v1/relay`.
    pub relay_ws: String,
    /// UDP/QUIC unreliable datagram relay, e.g. `host:7724`; empty when disabled.
    #[serde(default)]
    pub relay_quic: String,
    /// Built-in STUN endpoint as `host:port`; empty when the coord runs
    /// without one.
    #[serde(default)]
    pub stun: String,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct PeerEndpoints {
    pub device_id: String,
    pub endpoints: Vec<String>,
    pub last_seen_unix: u64,
}

/// SPAKE2 messages and payloads are hex encoded.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct EnrollStart {
    pub msg_a: String,
    /// Optional client-derived room key for user-chosen pairing phrases.
    /// When absent, the coord allocates a random 3-character nameplate.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub room: Option<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct EnrollStarted {
    pub nameplate: String,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct EnrollReply {
    pub msg_b: String,
    pub payload: String,
    /// Random hex token generated by the joining device; must be presented in
    /// `X-Topaz-Enroll-Token` when fetching `/v1/enroll/{nameplate}/finish`.
    #[serde(default)]
    pub finish_token: String,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct EnrollFinish {
    pub payload: String,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct SignalEnvelope {
    #[serde(rename = "type")]
    pub kind: String,
    pub from: String,
    pub to: String,
    #[serde(default)]
    pub endpoints: Vec<String>,
    #[serde(default)]
    pub text: String,
}

/// First frame on the TCP relay socket (postcard).
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct RelayHello {
    pub device_id: String,
    pub peer_id: String,
    pub time: u64,
    pub nonce: String,
    pub sig: String,
}
